from google.colab import files
from getpass import getpass
import os

os.environ["GOOGLE_API_KEY"] = "GEMINI API KEY"

#pdf loading
from langchain_community.document_loaders import PyPDFLoader
loader = PyPDFLoader("/content/RAGPaper.pdf")
documents = loader.load()

#split pdf into different chunks
from langchain_text_splitters import RecursiveCharacterTextSplitter
text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=1000,
    chunk_overlap=200
)

chunks = text_splitter.split_documents(documents)

print("Total chunks:", len(chunks))

#Create embeddings and the FAISS vector database
from langchain_google_genai import GoogleGenerativeAIEmbeddings
from langchain_community.vectorstores import FAISS
#converting chunks into embeddings and storing embedding to Faiss vector db
embeddings = GoogleGenerativeAIEmbeddings(
    model="gemini-embedding-001"
)

vectorstore = FAISS.from_documents(
    documents=chunks,
    embedding=embeddings
)

retriever = vectorstore.as_retriever(
    search_kwargs={"k": 4}
)

print("PDF indexed successfully!")

#Initialize the Gemini chat model
from langchain_google_genai import ChatGoogleGenerativeAI

llm = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    temperature=0
)

print("Gemini model initialized!")

#Create the RAG chatbot
from langchain_core.prompts import ChatPromptTemplate

prompt = ChatPromptTemplate.from_template("""
You are a PDF question-answering assistant.

Answer using only the context provided below.
If the answer is not available in the context,
say that you could not find it in the PDF.

Context:
{context}

Question:
{question}

Answer:
""")

def ask_pdf(question):
    relevant_docs = retriever.invoke(question)

    if not relevant_docs:
        print("No relevant information found.")
        return

    context = "\n\n".join(
        doc.page_content for doc in relevant_docs
    )

    chain = prompt | llm

    response = chain.invoke({
        "context": context,
        "question": question
    })

    print("\nAnswer:")
    print(response.content)

    pages = sorted({
        doc.metadata["page"] + 1
        for doc in relevant_docs
        if "page" in doc.metadata
    })

    print("\nSource PDF pages:", pages)

ask_pdf("What is the main objective of this research paper?")

ask_pdf("What methodology is used?")

ask_pdf("what is RAGs?")

ask_pdf("what is BART?")

